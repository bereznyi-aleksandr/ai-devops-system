#   L-S6-R11-01: билет принимается только в точном виде, который пишет Завод (JSON.stringify, порядок и набор полей
#   фиксированы, только ASCII, без перевода строки; повтор, лишнее или пропущенное поле, пробелы, другие знаки —
#   отказ без подписи); на экран выводятся только проверенные поля, по одному. M-S6-R11-01: показывается полный
#   head (40 знаков) и ссылка https://github.com/<репозиторий>/commit/<head> — оператор открывает её на телефоне;
#   что архив собран ровно из этого head, проверяет сервер (install_release.sh v0.4) по git-хешам)
# ИСПОЛНИТЕЛЬ: Claude (ГД Завода, сессия 9951b86f-676a-4a39-84f8-eeef3f226cd1)
# НАЗНАЧЕНИЕ: аудит ChatGPT S6-prep R10, M-S6-R9-01 и M-S6-R10-01 (критерии R11-1…R11-3) — подпись билета выпуска
#   НА ТЕЛЕФОНЕ оператора (Android, Termux), где созданы и лежат ключи; компьютер с агентом ключа и пароля не видит.
#   Решение оператора 2026-10-12: ключи — на телефоне, бесплатная программа Termux.
#   Claude присылает билет одной строкой base64 (билет — не секрет). Программа раскодирует его в новую временную
#   папку, проверяет точный вид, показывает поля, SHA-256 и остаток срока, просит ввести первые 8 знаков SHA-256 и
#   подписывает ровно эти байты ключом ~/.ssh/zavod_release_sign (пароль спрашивает ssh-keygen). Подпись печатается
#   для копирования в чат; Завод проверяет её в памяти по своему билету и ключу оператора, сервер — по release_signers.
# ВЫЗОВ (Termux): sh ~/zsign_phone.sh '<base64 билета>'
#   Файл скачивается один раз командой curl с GitHub по принятому аудитом коммиту и сверяется по полной сумме
#   SHA-256 из ответа аудитора (OD-5 шаг 7); локальная копия живёт только в телефоне.
# ОГРАНИЧЕНИЯ: только sh, base64, sha256sum, sed, grep, wc, date, ssh-keygen (пакеты Termux coreutils, grep и openssh).
#   Ничего не удаляет; временная папка остаётся в $TMPDIR телефона. Ключ и пароль программа не читает и не выводит.
set -eu
export LC_ALL=C
NS='zavod-release-ticket@v1'
KEY="$HOME/.ssh/zavod_release_sign"
[ $# -eq 1 ] || { echo 'usage: sh zsign_phone.sh <base64 билета>' >&2; exit 2; }
[ -f "$KEY" ] || { echo "Нет ключа $KEY. Не подписано." >&2; exit 2; }
D=$(mktemp -d)
F="$D/ticket.json"
printf '%s' "$1" | base64 -d > "$F" 2>/dev/null || { echo 'Строка билета повреждена. Не подписано.' >&2; exit 3; }
U='[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
N='(0|[1-9][0-9]{0,15})'
RE="^[{]\"v\":1,\"ticket_id\":\"$U\",\"issued_at\":$N,\"expires_at\":$N,\"head_sha\":\"[0-9a-f]{40}\",\"artifact_sha256\":\"[0-9a-f]{64}\",\"manifest_sha256\":\"[0-9a-f]{64}\",\"repo_id\":$N,\"repo_full_name\":\"[A-Za-z0-9_.-]{1,100}/[A-Za-z0-9_.-]{1,100}\",\"tenant_id\":\"$U\",\"work_item_id\":\"$U\"[}]\$"
[ "$(wc -l < "$F")" -eq 0 ] && grep -Eq "$RE" "$F" || { echo 'Это не билет выпуска Завода. Не подписано.' >&2; exit 3; }
field() { sed -n "s/.*\"$1\":\"\\{0,1\\}\\([^\",}]*\\).*/\\1/p" "$F"; }
REPO=$(field repo_full_name)
HEAD=$(field head_sha)
ISS=$(field issued_at)
EXP=$(field expires_at)
[ $((EXP - ISS)) -gt 0 ] && [ $((EXP - ISS)) -le 3600 ] || { echo 'Срок билета неверный. Не подписано.' >&2; exit 3; }
LEFT=$((EXP - $(date +%s)))
H=$(sha256sum "$F" | cut -d' ' -f1)
echo '--- билет выпуска ---'
echo "репозиторий: $REPO"
echo "head:        $HEAD"
echo "проверьте:   https://github.com/$REPO/commit/$HEAD"
echo "номер:       $(field ticket_id)"
echo "заказчик:    $(field tenant_id)"
echo "задача:      $(field work_item_id)"
echo "архив:       $(field artifact_sha256) (сервер сверит его с head)"
echo "SHA-256 билета: $H"
echo "До конца срока, минут: $((LEFT / 60))"
[ "$LEFT" -gt 0 ] || { echo 'Билет просрочен. Не подписано.' >&2; exit 4; }
printf 'Для подписи введите первые 8 знаков SHA-256: '
read -r ANS
[ "$ANS" = "$(printf '%s' "$H" | cut -c1-8)" ] || { echo 'Код не совпал. Не подписано.' >&2; exit 5; }
ssh-keygen -Y sign -q -n "$NS" -f "$KEY" "$F"
echo '--- скопируйте в чат всё от BEGIN до END ---'
cat "$F.sig"
